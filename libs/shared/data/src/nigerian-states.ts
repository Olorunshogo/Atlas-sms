// === Defaults

// Kaduna is the launch state and the default anywhere a state is required.
export const defaultStateName = 'Kaduna';

// === Lookup indexes

/* Built once at module load rather than scanning 37 states and their nested
   LGA arrays on every call. State and LGA selectors re-render often, so the
   repeated .find() cost is not hypothetical. Keys are lowercased names. */
const STATES_BY_NAME: Map<string, NigerianState> = new Map(
  nigerianStates.map((state) => [state.name.toLowerCase(), state]),
);

const LGAS_BY_STATE_AND_NAME: Map<string, NigerianLga> = new Map(
  nigerianStates.flatMap((state) =>
    state.lgas.map((lga): [string, NigerianLga] => [
      `${state.name.toLowerCase()}|${lga.name.toLowerCase()}`,
      lga,
    ]),
  ),
);

const EMPTY_LGAS: readonly NigerianLga[] = [];
const EMPTY_AREAS: readonly string[] = [];

// === Helpers

export const getStateByName = (name: string): NigerianState | undefined =>
  STATES_BY_NAME.get(name.trim().toLowerCase());

export const getLgasForState = (stateName: string): readonly NigerianLga[] =>
  getStateByName(stateName)?.lgas ?? EMPTY_LGAS;

export const getAreasForLga = (
  stateName: string,
  lgaName: string,
): readonly string[] => {
  const key = `${stateName.trim().toLowerCase()}|${lgaName.trim().toLowerCase()}`;
  return LGAS_BY_STATE_AND_NAME.get(key)?.areas ?? EMPTY_AREAS;
};

/*
 * Values are the human-readable names, not slugs, because that is what the API
 * stores and what defaultStateName compares against. `slug` stays on the type
 * for URLs and route params.
 */
export const stateSelectOptions = (): SelectOption[] =>
  nigerianStates.map((state) => ({ value: state.name, label: state.name }));

export const lgaSelectOptions = (stateName: string): SelectOption[] =>
  getLgasForState(stateName).map((lga) => ({
    value: lga.name,
    label: lga.name,
  }));
