// === Nigerian states dataset

/* All 36 states plus the Federal Capital Territory, with each state's capital
   and its full official list of Local Government Areas. 774 LGAs in total,
   which is the official national count.

   Area-level detail (wards/neighbourhoods inside an LGA) only exists where we
   have curated it by hand. Today that is Kaduna only, carried over from the
   original app-local dataset. Every other state's LGAs intentionally omit
   `areas` rather than guessing. */

import type { NigerianLga, NigerianState, SelectOption } from '@atlas/types';

// === Internal helpers

/* Most states carry no area detail, so their LGAs are written as plain name
   lists and lifted into NigerianLga objects once, at module load. Keeps the
   dataset readable without loosening the exported type. */
const lgas = (...names: readonly string[]): readonly NigerianLga[] =>
  names.map((name) => ({ name }));

